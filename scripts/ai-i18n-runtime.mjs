import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import { DEFAULT_LOCALE, LOCALE_STORAGE_KEY, SUPPORTED_LOCALES } from '../src/core/i18n/locales.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// Public HTML runs without Vue/Vite. Generate its small locale runtime from the same registry and AI resources.
export function renderAiLocaleRuntime(projectRoot = root) {
  const filename = path.join(projectRoot, 'src/core/i18n/locales.js')
  const source = ts.createSourceFile(
    filename,
    fs.readFileSync(filename, 'utf8'),
    ts.ScriptTarget.Latest,
    true
  )
  const localeFunctions = source.statements
    .filter(ts.isFunctionDeclaration)
    .map(node => node.getText(source).replace(/^export\s+/, ''))
    .join('\n')
  const messages = Object.fromEntries(
    SUPPORTED_LOCALES.map(locale => {
      const data = JSON.parse(
        fs.readFileSync(path.join(projectRoot, 'src/locales', locale, 'ai.json'), 'utf8')
      )
      for (const [key, value] of Object.entries(data)) {
        if (typeof value !== 'string' || /[|@]/.test(value))
          throw new Error(
            `Standalone AI messages support plain named parameters only: ${locale}:${key}`
          )
      }
      return [locale, data]
    })
  )
  return `// Generated by npm run i18n:sync-ai. Edit src/locales/*/ai.json and the locale registry instead.\n;(function () {
  if (window.opsAiI18n) return
  const DEFAULT_LOCALE = ${JSON.stringify(DEFAULT_LOCALE)}
  const LOCALE_STORAGE_KEY = ${JSON.stringify(LOCALE_STORAGE_KEY)}
  const SUPPORTED_LOCALES = ${JSON.stringify(SUPPORTED_LOCALES)}
  const messages = ${JSON.stringify(messages, null, 2)}
  ${localeFunctions}
  let storage
  try { storage = window.localStorage } catch { /* Browser language remains available when storage is denied. */ }
  const languages = navigator.languages || [navigator.language].filter(Boolean)
  let preference
  try { preference = storage?.getItem(LOCALE_STORAGE_KEY) } catch { /* Keep the browser language fallback. */ }
  let locale = resolveInitialLocale(preference, languages)
  const listeners = new Set()
  function t(key, params = {}) {
    const text = messages[locale]?.[key] ?? messages[DEFAULT_LOCALE]?.[key] ?? key
    return text.replace(/\\{(\\w+)\\}/g, (placeholder, name) => String(params[name] ?? placeholder))
  }
  function updateDocument() {
    document.documentElement.lang = locale
    document.title = t(document.documentElement.dataset.aiTitle || 'pageTitle')
  }
  window.opsAiI18n = Object.freeze({
    t,
    get locale() { return locale },
    subscribe(listener) { listeners.add(listener); listener(); return () => listeners.delete(listener) }
  })
  updateDocument()
  window.addEventListener('storage', event => {
    if (event.key !== LOCALE_STORAGE_KEY && event.key !== null) return
    if (event.storageArea && storage && event.storageArea !== storage) return
    const next = resolveInitialLocale(event.newValue, languages)
    if (next === locale) return
    locale = next
    updateDocument()
    listeners.forEach(listener => listener())
  })
})()\n`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'public/aiops-i18n.js'), renderAiLocaleRuntime())
  console.log('Updated public/aiops-i18n.js from the registered AI messages.')
}
